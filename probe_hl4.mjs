import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('PAGEERROR', String(e)));
await page.goto('http://localhost:8096/', { waitUntil: 'load' });
await page.waitForSelector('.list-item', { timeout: 20000 });
await page.click('.list-item:has-text("周末看展记录") .item-title-text');
await page.waitForSelector('.detail .ed-line', { timeout: 8000 });
const dump = async (label) => console.log(label, await page.evaluate(() => {
  const e = document.querySelector('[data-bid="de1"]');
  if (!e) return 'de1 GONE';
  const nodes = [];
  const w = document.createTreeWalker(e, NodeFilter.SHOW_TEXT);
  let n; while (n = w.nextNode()) nodes.push(n.textContent);
  return { html: e.innerHTML, nodes };
}));
await dump('initial');
await page.click('.detail .ed-line >> nth=0');
await page.keyboard.press('End');
await page.keyboard.type('前==重点==');
await page.waitForTimeout(300);
await dump('after ==重点==');
await page.keyboard.type('后');
await page.waitForTimeout(300);
await dump('after 后');
await page.keyboard.press('Enter');
await page.waitForTimeout(500);
console.log('ALL', await page.evaluate(() => [...document.querySelectorAll('.detail [data-bid]')].map(e => ({ bid: e.dataset.bid, html: e.innerHTML.slice(0, 120) }))));
await browser.close();
