import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
for (const k of ['http_proxy', 'https_proxy', 'HTTP_PROXY', 'HTTPS_PROXY', 'all_proxy', 'ALL_PROXY']) delete process.env[k];
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const page = await (await browser.newContext({ viewport: { width: 1280, height: 800 } })).newPage();
page.on('console', (m) => console.log('CONSOLE', m.type(), m.text().slice(0, 200)));
page.on('pageerror', (e) => console.log('PAGEERROR', String(e).slice(0, 300)));
page.on('requestfailed', (r) => console.log('REQFAIL', r.url().slice(0, 120), r.failure()?.errorText));
await page.goto('http://localhost:8931/', { waitUntil: 'load' }).catch((e) => console.log('GOTO ERR', String(e).slice(0, 150)));
await page.waitForTimeout(9000);
console.log('TITLE', await page.title());
console.log('HTML', (await page.evaluate(() => document.body.innerHTML.slice(0, 600))).replace(/\n/g, ' '));
await page.screenshot({ path: '/tmp/dbg_mirror.png' });
await browser.close();
