import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 420, height: 900 }, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('PAGEERROR:', String(e).slice(0, 200)));
page.on('console', m => { const t = m.text(); if (t.includes('Error') || t.includes('error')) console.log('CONSOLE:', t.slice(0, 160)); });
await page.goto('http://localhost:8095/', { waitUntil: 'load' });
await page.waitForTimeout(14000);
await page.screenshot({ path: process.env.HOME + '/workspace/mynote-shots-round6/20-list-ready.png' });
await page.touchscreen.tap(210, 765);
await page.waitForTimeout(3500);
await page.screenshot({ path: process.env.HOME + '/workspace/mynote-shots-round6/21-music-open.png' });
const diag = await page.evaluate(() => { try { return JSON.parse(localStorage.getItem('mynote_diag_v1') || '[]').map(e => String(e)).slice(-5); } catch { return ['?']; } });
console.log('DIAG:', JSON.stringify(diag, null, 0));
await browser.close();
