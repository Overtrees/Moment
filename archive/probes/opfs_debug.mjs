import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe });
const page = await browser.newPage({ viewport: { width: 420, height: 900 } });
page.on('pageerror', e => console.log('PAGEERROR', String(e)));
page.on('filechooser', () => console.log('FILECHOOSER FIRED'));
await page.goto('http://127.0.0.1:8095/', { waitUntil: 'networkidle' });
await page.waitForTimeout(6000);
await page.mouse.click(365, 42);
await page.waitForTimeout(2500);
const inputs = await page.evaluate(() => document.querySelectorAll('input[type=file]').length);
console.log('file inputs in DOM:', inputs);
await page.screenshot({ path: '/tmp/opfs-debug.png' });
await browser.close();
