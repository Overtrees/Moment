import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('PAGEERROR', String(e)));
await page.goto('http://localhost:8096/', { waitUntil: 'load' });
await page.waitForSelector('.list-item', { timeout: 20000 });
await page.click('.new-card-title');
await page.waitForSelector('#editor-root [data-bid]', { timeout: 10000 });
await page.waitForTimeout(400);
const bl = await page.$$eval('#editor-root [data-bid]', els => els.map(e => e.dataset.bid));
await page.click(`[data-bid="${bl[0]}"]`);
await page.keyboard.type('UndoMe');
await page.waitForTimeout(300);
await page.keyboard.press('Control+z');
await page.waitForTimeout(900);
console.log('active', await page.evaluate(() => document.activeElement && (document.activeElement.dataset.bid || document.activeElement.tagName)));
console.log('hasFocusFn', await page.evaluate(() => typeof window.__mnFocus));
console.log('blocks', await page.evaluate(() => [...document.querySelectorAll('#editor-root [data-bid]')].map(e => ({ bid: e.dataset.bid, text: e.innerText }))));
console.log('diag tail', await page.evaluate(() => (localStorage.getItem('mynote_diag_v1') || '').split('\n').slice(-8).join('\n')));
await browser.close();
