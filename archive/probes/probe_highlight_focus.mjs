import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('PAGEERROR', String(e)));
await page.goto('http://localhost:8096/', { waitUntil: 'load' });
await page.waitForSelector('.list-item', { timeout: 20000 });
await page.click('.list-item:has-text("周末看展记录") .item-title-text');
await page.waitForSelector('.detail', { timeout: 8000 });
await page.waitForTimeout(500);
console.log('BLOCKS', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('.detail [data-bid], .detail .md-hit')].map(e => ({tag:e.tagName, cls:e.className, bid:e.getAttribute('data-bid'), text:(e.innerText||'').slice(0,40)}) )), null, 1));
await page.click('.detail .ed-line >> nth=0');
console.log('ACTIVE after click', await page.evaluate(() => ({tag:document.activeElement.tagName, cls:document.activeElement.className, bid:document.activeElement.getAttribute('data-bid')})));
await page.keyboard.press('End');
await page.keyboard.type('前==重点==后');
await page.waitForTimeout(600);
console.log('ACTIVE after type', await page.evaluate(() => ({tag:document.activeElement.tagName, cls:document.activeElement.className, bid:document.activeElement.getAttribute('data-bid')})));
console.log('DE1', await page.evaluate(() => { const e=document.querySelector('[data-bid="de1"]'); return e ? {cls:e.className, html:e.innerHTML, text:e.innerText} : null; }));
console.log('MARKS', await page.evaluate(() => [...document.querySelectorAll('.detail mark, .detail .mynote-highlight')].map(e=>({tag:e.tagName, cls:e.className, text:e.textContent}))));
await browser.close();
