import { chromium } from 'playwright-core';
const CHROME = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const b = await chromium.launch({ executablePath: CHROME, args: ['--no-sandbox'] });
const page = await b.newPage({ viewport: { width: 420, height: 880 } });
const errors = [];
page.on('pageerror', e => errors.push(String(e).slice(0, 160)));
await page.goto('http://127.0.0.1:8092/', { waitUntil: 'load' });
await page.waitForTimeout(9000);
await page.mouse.click(150, 200);
await page.waitForTimeout(5000);
await page.locator('canvas').first().screenshot({ path: '/tmp/app_editor.png' });
// 在正文第一段末尾打字
await page.mouse.click(300, 130);
await page.waitForTimeout(600);
await page.keyboard.type('PERSIST-OK');
await page.waitForTimeout(800);
await page.mouse.click(392, 30);
await page.waitForTimeout(1500);
await page.mouse.click(24, 30);
await page.waitForTimeout(1200);
await page.reload({ waitUntil: 'load' });
await page.waitForTimeout(9000);
await page.mouse.click(150, 200);
await page.waitForTimeout(5000);
await page.locator('canvas').first().screenshot({ path: '/tmp/app_editor2.png' });
console.log('errors:', JSON.stringify(errors.slice(0, 3)));
await b.close();
