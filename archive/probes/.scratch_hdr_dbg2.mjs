import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, hasTouch: true, acceptDownloads: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', String(e).slice(0, 160)));
await page.goto('http://localhost:8246/', { waitUntil: 'load' });
await page.waitForTimeout(2500);
await page.$eval('h1.page-title', (e) => e.click());
await page.waitForSelector('.page-content', { timeout: 8000 });
await page.click('.set-row:has-text("备份与恢复")');
await page.waitForSelector('#file-import', { state: 'attached', timeout: 8000 });
await page.setInputFiles('#file-import', '/tmp/hdrprobe/b1.zip');
await page.waitForSelector('.backup-modal', { timeout: 8000 });
await page.click('.backup-modal .backup-btn.primary');
await page.waitForFunction(() => document.querySelector('.backup-toast')?.innerText.includes('已导入'), null, { timeout: 15000 });
await page.click('.editor-fab.left');
await page.waitForSelector('.seg-row', { timeout: 8000 });
await page.click('.editor-fab.left');
await page.waitForSelector('.glass-search-trigger', { state: 'attached', timeout: 10000 });
console.log('cards:', await page.evaluate(() => [...document.querySelectorAll('.img-card, .list-item')].map(e => e.className + ' :: ' + e.textContent.slice(0, 30))));
// try clicking the card container of 短题三
const card = page.locator('.img-card, .list-item', { hasText: '短题三' }).first();
await card.scrollIntoViewIfNeeded().catch(() => {});
await card.click({ timeout: 5000 }).catch(e => console.log('card click err', String(e).slice(0, 120)));
await page.waitForTimeout(1500);
console.log('detail present:', await page.evaluate(() => !!document.querySelector('.detail')));
console.log('dock:', await page.evaluate(() => document.querySelector('.editor-title-dock')?.className || null));
await page.screenshot({ path: '/tmp/hdrprobe/editor.png' });
await browser.close();
