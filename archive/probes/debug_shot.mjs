import { chromium } from 'playwright-core';
const EXE = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: EXE, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 420, height: 900 }, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('[pageerror]', String(e).slice(0, 300)));
page.on('console', (m) => { const t = m.text(); if (t.includes('Error') || t.includes('error') || t.includes('Exception')) console.log('[console]', t.slice(0, 300)); });
await page.goto('http://127.0.0.1:8099/', { waitUntil: 'load' });
await page.waitForTimeout(15000);
await page.screenshot({ path: process.env.HOME + '/workspace/mynote-shots-round3/debug-build.png' });
const diag = await page.evaluate(() => (localStorage.getItem('mynote_diag_v1') || '').slice(-1200));
console.log('DIAG:', diag);
await browser.close();
console.log('done');
