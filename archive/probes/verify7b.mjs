import { chromium } from 'playwright-core';
const EXE = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: EXE, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 420, height: 900 }, hasTouch: true });
const page = await ctx.newPage();
const logs = [];
page.on('console', m => logs.push(m.type() + ': ' + m.text().slice(0, 200)));
page.on('pageerror', e => logs.push('PAGEERROR: ' + String(e).slice(0, 200)));
ctx.on('page', p => logs.push('POPUP: ' + p.url().slice(0, 140)));
await page.goto('http://localhost:8095/', { waitUntil: 'load' });
await page.waitForTimeout(10000);
await page.touchscreen.tap(52, 84);
await page.waitForTimeout(2000);
await page.touchscreen.tap(210, 328);
await page.waitForTimeout(2000);
logs.length = 0;
await page.touchscreen.tap(210, 570);
await page.waitForTimeout(6000);
await page.screenshot({ path: process.env.HOME + '/workspace/mynote-shots-round6/07-after-connect.png' });
const diag = await page.evaluate(() => { try { return (localStorage.getItem('mynote_diag_v1') || '').slice(-500); } catch (e) { return 'ERR'; } });
console.log('DIAG:', diag);
console.log('COOP-related:', logs.filter(l => /opener|COOP|Cross-Origin|popup/i.test(l)).join(' | ') || '(none)');
console.log('Google-related:', logs.filter(l => /google|gsi|accounts/i.test(l)).slice(0, 4).join(' | ') || '(none)');
console.log('Errors:', logs.filter(l => /^error|PAGEERROR/.test(l)).slice(0, 4).join(' | ') || '(none)');
await browser.close();
