import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('PAGEERROR', String(e)));
const active = async (label) => console.log(label, await page.evaluate(() => {
  const a = document.activeElement;
  const sel = window.getSelection();
  return { bid: a && a.getAttribute('data-bid'), cls: a && a.className, selBid: sel && sel.rangeCount ? (sel.getRangeAt(0).startContainer.parentElement.closest('[data-bid]') || {}).dataset?.bid : null, selText: sel && sel.rangeCount ? sel.getRangeAt(0).startContainer.textContent.slice(0, 30) : null };
}));
await page.goto('http://localhost:8096/', { waitUntil: 'load' });
await page.waitForSelector('.list-item', { timeout: 20000 });
await page.click('.list-item:has-text("周末看展记录") .item-title-text');
await page.waitForSelector('.detail .ed-line', { timeout: 8000 });
await page.click('.detail .ed-line >> nth=0');
await page.keyboard.press('End');
await page.keyboard.type('前==重点==后');
await page.waitForTimeout(500);
await active('after step1 type');
await page.keyboard.press('Enter');
await page.waitForTimeout(400);
await active('after step2 Enter');
await page.keyboard.type('/');
await page.waitForSelector('.slash-panel .slash-row[data-act="highlight"]', { timeout: 8000 });
await page.click('.slash-panel .slash-row[data-act="highlight"]');
await page.waitForTimeout(400);
await active('after slash highlight');
await page.keyboard.type('斜杠亮');
await page.waitForTimeout(400);
await active('after type 斜杠亮');
await page.keyboard.press('Enter');
await page.waitForTimeout(400);
await active('after step3 Enter');
await page.keyboard.type('包裹测试');
await page.waitForTimeout(400);
await active('after type 包裹测试');
console.log('BLOCKS', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('.detail [data-bid]')].map(e => ({ bid: e.dataset.bid, text: (e.innerText || '').slice(0, 50) }))), null, 1));
await browser.close();
