import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 420, height: 900 }, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('PAGEERROR:', String(e).slice(0, 140)));
const shot = (n) => page.screenshot({ path: process.env.HOME + '/workspace/mynote-shots-round6/' + n });
await page.goto('http://localhost:8095/', { waitUntil: 'load' });
await page.waitForTimeout(11000);
await page.touchscreen.tap(210, 479);
await page.waitForTimeout(2500);
await page.touchscreen.tap(150, 700);
await page.waitForTimeout(600);
await page.keyboard.press('End');
await page.keyboard.press('Enter');
await page.keyboard.type('/');
await page.waitForTimeout(700);
await page.keyboard.type('音乐');
await page.waitForTimeout(900);
await shot('43-slash-music-filter.png');
await page.touchscreen.tap(210, 462);
await page.waitForTimeout(1400);
await shot('44-card-edit-overlay.png');
await page.keyboard.type('https://music.163.com/song?id=123');
await page.waitForTimeout(500);
await shot('45-card-edit-typed.png');
await page.touchscreen.tap(210, 180); // 点外提交
await page.waitForTimeout(2000);
await shot('46-card-committed.png');
const diag = await page.evaluate(() => { try { return JSON.parse(localStorage.getItem('mynote_diag_v1') || '[]').slice(-6); } catch (e) { return ['ERR']; } });
console.log('DIAG:', JSON.stringify(diag).slice(0, 500));
await browser.close();
