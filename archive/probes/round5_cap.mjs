import { chromium } from 'playwright-core';
const EXE = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: EXE, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 420, height: 900 }, hasTouch: true, isMobile: true, serviceWorkers: 'block' });
const page = await ctx.newPage();
await page.goto('http://127.0.0.1:8095/', { waitUntil: 'load' });
await page.waitForTimeout(6000);
await page.touchscreen.tap(210, 320);
await page.waitForTimeout(3000);
await page.screenshot({ path: process.env.HOME + '/workspace/mynote-shots-round4/50-capsule-fix.png', clip: { x: 120, y: 0, width: 180, height: 190 } });
await browser.close();
console.log('ok');
