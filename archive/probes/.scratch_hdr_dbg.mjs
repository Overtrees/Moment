import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, hasTouch: true, acceptDownloads: true });
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', String(e).slice(0, 200)));
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0, 200)); });
await page.goto('http://localhost:8246/', { waitUntil: 'load' });
await page.waitForTimeout(4000);
console.log('initial html classes:', await page.evaluate(() => document.body.innerHTML.slice(0, 300)));
await page.$eval('h1.page-title', (e) => e.click());
await page.waitForSelector('.page-content', { timeout: 8000 });
await page.click('.set-row:has-text("备份与恢复")');
await page.waitForSelector('#file-import', { state: 'attached', timeout: 8000 });
await page.setInputFiles('#file-import', '/tmp/hdrprobe/fixture.zip');
await page.waitForSelector('.backup-modal', { timeout: 8000 });
await page.click('.backup-modal .backup-btn.primary');
await page.waitForTimeout(3000);
console.log('toast:', await page.evaluate(() => document.querySelector('.backup-toast')?.innerText || 'none'));
await page.click('.editor-fab.left');
await page.waitForTimeout(1200);
await page.click('.editor-fab.left').catch(e => console.log('fab2', String(e).slice(0,100)));
await page.waitForTimeout(1500);
console.log('list titles:', await page.evaluate(() => [...document.querySelectorAll('.img-card-title-text, .list-item .item-title-text')].map(e => e.textContent)));
await page.screenshot({ path: '/tmp/hdrprobe/list.png' });
await browser.close();
