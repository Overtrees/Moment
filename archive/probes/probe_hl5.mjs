import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, hasTouch: true });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('PAGEERROR', String(e)));
await page.goto('http://localhost:8096/', { waitUntil: 'load' });
await page.waitForSelector('.list-item', { timeout: 20000 });
await page.click('.new-card-title');
await page.waitForSelector('#editor-root [data-bid]', { timeout: 10000 });
await page.waitForTimeout(400);
const blocks = () => page.$$eval('#editor-root [data-bid]', els => els.map(e => ({ bid: e.dataset.bid, bt: e.dataset.btype, text: e.innerText.replace(/\n$/, '') })));
let bl = await blocks();
await page.click(`[data-bid="${bl[0].bid}"]`);
await page.keyboard.type('/');
await page.waitForSelector('#slash-panel', { timeout: 5000 });
await page.locator('#slash-panel .slash-row[data-act="todo"]').first().click();
await page.waitForTimeout(500);
bl = await blocks();
console.log('after todo apply', JSON.stringify(bl));
const tb = bl[0].bid;
await page.click(`[data-bid="${tb}"]`);
await page.keyboard.type('BuyMilk');
await page.evaluate((bid) => {
  const el = document.querySelector(`[data-bid="${bid}"]`);
  const n = el.firstChild;
  const r = document.createRange(); r.setStart(n, 3); r.collapse(true);
  const s = window.getSelection(); s.removeAllRanges(); s.addRange(r);
}, tb);
await page.keyboard.press('Enter');
await page.waitForTimeout(500);
bl = await blocks();
console.log('after split', JSON.stringify(bl));
const second = bl[1].bid;
await page.click(`[data-bid="${second}"]`);
console.log('active after click', await page.evaluate(() => document.activeElement && document.activeElement.dataset && document.activeElement.dataset.bid));
await page.keyboard.press('Control+a');
await page.waitForTimeout(200);
console.log('selection', await page.evaluate(() => { const s = window.getSelection(); return { text: s.toString(), rangeCount: s.rangeCount }; }));
await page.keyboard.press('Backspace');
await page.waitForTimeout(300);
bl = await blocks();
console.log('after clear', JSON.stringify(bl));
await page.keyboard.press('Enter');
await page.waitForTimeout(500);
bl = await blocks();
console.log('after enter on empty todo', JSON.stringify(bl));
await browser.close();
