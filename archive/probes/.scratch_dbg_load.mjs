import { chromium } from 'playwright-core';
const exe = process.env.HOME + '/.cache/ms-playwright/chromium_headless_shell-1255/chrome-headless-shell-linux64/chrome-headless-shell';
const browser = await chromium.launch({ executablePath: exe, args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
page.on('console', (m) => console.log('CONSOLE', m.type(), m.text().slice(0, 160)));
page.on('pageerror', (e) => console.log('PAGEERROR', String(e).slice(0, 200)));
await page.goto('http://127.0.0.1:8347/', { waitUntil: 'load' });
await page.waitForTimeout(20000);
console.log('list items:', await page.evaluate(() => document.querySelectorAll('.list-item, .img-card').length));
console.log('body head:', await page.evaluate(() => document.body.innerText.slice(0, 200)));
await browser.close();
